; =============================================================================
; LESSON 23 — EXERCISE 1 SOLUTION: A Third Level
; =============================================================================
; Part 3: Playfield
;
; Exercise: add a third level table and a three-way selector.
;
; The technique: Level counts 0, 1, 2 and wraps.  The VBLANK pointer setup
; gains a third branch; the kernel and the row format are unchanged.
; Level 3 "the deep keep" puts the divider at rows 30-32 and opens an
; eight-chunk door (PF2 = $0F), then uses the pillar/open blocks in the
; lower half.
;
; Debugger checkpoints: LevelSwitch (A = the new level, every 240 frames;
; the sequence is 1, 2, 0), RowStore (one hit per line).
;
; Build: acme -f plain -o build/lesson23-ex1.bin \
;        lessons/part3-playfield/23-data-driven-playfield/exercise-01-solution.asm
; Run:   stella build/lesson23-ex1.bin
; =============================================================================

    !cpu 6502

; --- Include hardware definitions; +clean_start boots the machine ---
    !source "include/vcs.asm"
    !source "include/macro.asm"

; =============================================================================
; PROGRAM CONSTANTS
; =============================================================================
VBLANK_TIMER   = 44     ; TIM64T ticks for exactly 37 lines
OVERSCAN_TIMER = 36     ; TIM64T ticks for exactly 30 lines
VISIBLE_LINES  = 192
LEVEL_FRAMES   = 240    ; ~4 seconds per level

; --- Zero-page variables (RAM $80-$FF; +clean_start zeroes them) ---
FrameCounter   = $80
Level          = $81    ; 0/1/2 = Level1/2/3 tables
Ptr0           = $82    ; 2 bytes each: the PF0/PF1/PF2 table bases
Ptr1           = $84
Ptr2           = $86
Tmp0           = $88    ; the current row's three bytes
Tmp1           = $89
Tmp2           = $8A

; =============================================================================
; ROM START — cartridge space ($F000-$FFFF)
; =============================================================================
    * = $F000

; =============================================================================
; ENTRY POINT
; =============================================================================
Reset:
    +clean_start            ; zero TIA + RAM; Level = 0 (Level 1)

; =============================================================================
; MAIN LOOP — one pass = one frame = 262 scanlines
; =============================================================================
StartFrame:                 ; debugger checkpoint: VSYNC's first line (Stella: 259)
    +vsync

VblankStart:                ; debugger checkpoint: VBLANK's first line (Stella: 0)
    LDA #$02
    STA VBLANK
    +set_timer VBLANK_TIMER

; --- the level tick: switch every LEVEL_FRAMES frames ---
    INC FrameCounter
    LDA FrameCounter
    CMP #LEVEL_FRAMES
    BNE VblankSetLevel
    LDA #$00
    STA FrameCounter
    LDA Level
    CLC
    ADC #$01
    CMP #3
    BNE LevelStore
    LDA #$00
LevelStore:
LevelSwitch:                ; debugger checkpoint: A = the new level (flip only)
    STA Level

; --- point the three tables at the current level ---
VblankSetLevel:
    LDA Level
    CMP #1
    BEQ VblankLevel2
    CMP #2
    BEQ VblankLevel3
VblankLevel1:
    LDA #<Level1PF0
    STA Ptr0
    LDA #>Level1PF0
    STA Ptr0+1
    LDA #<Level1PF1
    STA Ptr1
    LDA #>Level1PF1
    STA Ptr1+1
    LDA #<Level1PF2
    STA Ptr2
    LDA #>Level1PF2
    STA Ptr2+1
    JMP VblankPreload

VblankLevel2:
    LDA #<Level2PF0
    STA Ptr0
    LDA #>Level2PF0
    STA Ptr0+1
    LDA #<Level2PF1
    STA Ptr1
    LDA #>Level2PF1
    STA Ptr1+1
    LDA #<Level2PF2
    STA Ptr2
    LDA #>Level2PF2
    STA Ptr2+1
    JMP VblankPreload

VblankLevel3:
    LDA #<Level3PF0
    STA Ptr0
    LDA #>Level3PF0
    STA Ptr0+1
    LDA #<Level3PF1
    STA Ptr1
    LDA #>Level3PF1
    STA Ptr1+1
    LDA #<Level3PF2
    STA Ptr2
    LDA #>Level3PF2
    STA Ptr2+1
    JMP VblankPreload

; --- preload row 0 into the row temps ---
VblankPreload:
    LDY #0
    LDA (Ptr0),Y
    STA Tmp0
    LDA (Ptr1),Y
    STA Tmp1
    LDA (Ptr2),Y
    STA Tmp2

    LDA #$C8
    STA COLUPF              ; green
    LDA #$02
    STA COLUBK              ; dark neutral
    LDA #$01
    STA CTRLPF              ; reflect: the maze is symmetric

    LDX #VISIBLE_LINES
    +wait_timer

; -----------------------------------------------------------------------------
; VISIBLE — one table row per line
; -----------------------------------------------------------------------------
    LDA #$00
    STA VBLANK              ; release the beam on line 37
VisibleStart:               ; debugger checkpoint: the picture's first line (37)
    LDA Tmp0
    STA PF0
    LDA Tmp1
    STA PF1
    LDA Tmp2
    STA PF2
RowStore:                   ; debugger checkpoint: A = the PF2 byte
    INY                     ; the next row
    LDA (Ptr0),Y
    STA Tmp0
    LDA (Ptr1),Y
    STA Tmp1
    LDA (Ptr2),Y
    STA Tmp2
    STA WSYNC               ; park the rest of this line
    DEX
    BNE VisibleStart

; -----------------------------------------------------------------------------
; OVERSCAN — 30 lines; blank-on lands in line 229's HBLANK
; -----------------------------------------------------------------------------
OverscanStart:
    LDA #$02
    STA VBLANK
    +set_timer OVERSCAN_TIMER
    +wait_timer
    JMP StartFrame

