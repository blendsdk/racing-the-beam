; =============================================================================
; LESSON 71 — EXERCISE 1 SOLUTION: FOG OF WAR — Racing the Beam
; =============================================================================
; Part 10: Capstone Projects
;
; What this exercise adds:
;   The maze is dark.  Only the cells within two Manhattan steps of the
;   player's cell are drawn; every other wall cell is black.  The fog is
;   rebuilt every frame in VBLANK: a five-row window of playfield bytes is
;   computed from the player's row and column, and an 11-byte index table
;   maps each maze row to its window row or to $FF ("all dark").  The kernel
;   reads the fog bytes instead of the static MazePF table.
;
;   The sprites stay visible: the player, the enemies, the key and the
;   status band are unchanged, so an enemy can appear out of the dark.  The
;   maze's static data is still in maze-data.inc; the fog only masks it.
;
; The rest of the program is the main lesson: a generated mirror maze,
; cell-by-cell movement, two greedy enemies, three sequential keys, the
; scripted demo, and the win/lose states.
;
; The screen (192 visible lines):
;   picture lines 0-7     the status band: three key slots and their
;                         reflect-mode mirrors.
;   picture lines 8-15    the first maze row's setup: line 8 clears the icon
;                         playfield, line 9 loads the fog window's row 0,
;                         line 13 decodes object row 0, line 14 clears the
;                         graphics latches, and line 15 writes the ball and
;                         P0 (VDEL delivers them on line 16).  P1 is written
;                         immediately on line 16's first line.
;   picture lines 16-191  the maze: 11 maze rows x 16 lines = 176 lines.
;                         Each maze row holds four 4-line object rows; the
;                         44-byte ObjRowTable has one 4-bit byte per object
;                         row.  The PF bytes are the fog window's bytes for
;                         the row (or zero when the row is dark).
;   8 + 8 + 176 = 192.
;
; The fog window:
;   FogPF is 5 rows x 3 PF bytes.  FogIndex (11 bytes) is the row -> window
;   index table: rows within two of PlayerRow get (row - PlayerRow + 2) * 3;
;   the others get $FF.  The kernel's LoadFogPF turns a row into the three
;   PF bytes, and the line-3 prefetch loads the next row's bytes one maze
;   row early, exactly like the main's static PF prefetch.
;
;   For a row at vertical distance d (0..2), the visible columns are
;   PlayerCol - (2 - d) .. PlayerCol + (2 - d), clamped to 0..19.  Each
;   visible column maps to its unique cell with the mirror transform, and
;   CellPF0/1/2 supply that cell's two chunks.  The three mask bytes are
;   ANDed with the static MazePF row, so a visible open cell stays open.
;
; RAM map (the exercise adds two regions; the main's map is unchanged):
;   $80-$AB  ObjRowTable
;   $AC-$C7  the main's 28 game variables
;   $C8      PFIdx         the next maze row for LoadFogPF, 0..11
;   $C9-$DD  the main's scratch
;   $DE-$EC  FogPF         15 bytes: the five visible rows x 3 PF bytes
;   $ED-$F7  FogIndex      11 bytes: row -> window index (0,3,6,9,12,$FF)
;   $F8-$FF  stack
;
; Checkpoints: the main's checkpoints, unchanged.  The demo is the main's
; route; the generator's placements are unchanged.
;
; Build: acme -f plain -o build/exercise-01-solution.bin \
;        lessons/part10-capstones/71-maze-explorer/exercise-01-solution.asm
; Run:   stella build/exercise-01-solution.bin
; =============================================================================
;
; The frame (NTSC): 3 VSYNC + 37 VBLANK + 192 picture + 30 overscan = 262.
;   StartFrame is scanline 259, VblankStart 0, BodyStart 37, MazeRowStart 53,
;   OverscanStart 229.
;
; The mirror maze:
;   Ten unique columns x eleven rows; each cell is 8x16 pixels, two playfield
;   chunks.  CTRLPF bit 0 = 1 selects reflect mode, so visible columns 0-9
;   are the unique maze and visible columns 10-19 are its mirror.  The
;   transform is col < 10 ? col : 19 - col; a wall at unique column 4 blocks
;   visible columns 4 and 15.  The generator opens the seam at the right edge
;   of unique column 9 on two even rows so the player can cross between the
;   two visible copies.
;
; The storage:
;   maze-data.inc is generated by lesson71-generate.py from maze-spec.txt.
;   MazePF is 11 rows x 3 bytes (PF0 chunks 0-3, PF1 chunks 4-11, PF2 chunks
;   12-19); a wall cell sets both of its chunks, an open cell is empty.
;   MazeWalls is 11 rows x 2 bytes; bit 9 is the leftmost unique column and
;   the first byte holds bits 9..2 (column 0 in bit 7), the second bits 1..0
;   (column 8 in bit 1, column 9 in bit 0).  1 = wall.
;   KeyCells is 3 x 2 (visible column, row) in collection order; EnemyCells
;   is 2 x 2; DemoPath is the scripted route, one direction per step
;   (0=up, 1=down, 2=left, 3=right).
;
; The movement:
;   The player starts at (0,10).  A joystick direction tries the next cell;
;   a held direction repeats every 8 frames.  The target's visible column is
;   mirrored to the unique wall map, and the row indexes MazeWalls.  A wall
;   blocks; an open cell commits the move.  The player is clamped to the
;   20 x 11 visible grid.  The sprite position is X = col * 8 and
;   Y = 16 + row * 16, set by the positioners and the object row table.
;
; The enemies:
;   Two enemies move every 8 frames.  Each chooses the axis with the larger
;   distance to the player; if that cell is blocked, it tries the other axis;
;   if both are blocked it stays.  An enemy already on the player's cell
;   stays (a zero delta is the catch).  The mirror transform selects the wall
;   map byte.  The cell compare runs after the player's move and after the
;   enemies move; an enemy in the player's cell sets the lose state.
;
; The keys:
;   The ball is the current key (8x8, CTRLPF bits 4-5 = 11).  Entering its
;   cell increments KeysLeft, moves the ball to the next KeyCells entry, and
;   fills the next status slot.  The third key sets the win state.  The keys
;   are sequential: the ball always shows the next key to collect.  The key
;   blinks on Frame bit 4: it shares COLUPF with the walls, and the blink
;   makes the 8x8 block read even when it touches a dead end's wall.
;
; The colours:
;   COLUP0 (P0 and M0) is gold; the player is the 4-pixel bar and M0 the
;   8-pixel block of enemy 2.  COLUP1 (enemy 1) is red.  COLUPF (the walls,
;   the key slots and the ball) is blue; the win wave is green and the lose
;   wave is red.  P0 and M0 share one colour register, so they share gold.
;
; The win and the lose:
;   GameState 0 = play, 1 = win, 2 = lose.  The win flashes the playfield
;   green on Frame bit 4; the lose flashes it red.  Fire restarts: the
;   player returns to (0,10), the enemies to their generated starts, and the
;   key sequence to the first key.
;
; The auto-demo:
;   After 120 frames with no joystick direction the scripted demo takes
;   over and walks one cell every 5 frames along the generated DemoPath.
;   The route visits the three keys in collection order; the generator
;   simulates the greedy enemies against the route and only commits a start
;   pair that is not caught.  Any joystick direction returns control to the
;   player.  The demo is disclosed: the 2 s capture shows the start, the 6 s
;   capture shows the first key collected, and the 10 s capture shows the
;   win.
;
; RAM map (the exact map; +clean_start zeroes every byte):
;   $80-$AB  ObjRowTable   44 bytes, one 4-bit byte per 4-line object row:
;                          bit 0 player, bit 1 enemy 1, bit 2 enemy 2,
;                          bit 3 key
;   $AC      PlayerCol     visible column, 0..19
;   $AD      PlayerRow     row, 0..10
;   $AE      PrevJoy       the last frame's SWCHA high nibble
;   $AF      MoveTimer     the held-direction repeat counter
;   $B0      Enemy1Col     visible column, 0..19
;   $B1      Enemy1Row     0..10
;   $B2      Enemy2Col
;   $B3      Enemy2Row
;   $B4      EnemyTimer    8..1; at zero both enemies step
;   $B5      KeyCol        the current key's visible column
;   $B6      KeyRow        the current key's row
;   $B7      KeysLeft      collected keys, 0..3
;   $B8      KeyIndex      the next KeyCells entry, 0..2
;   $B9      Frame         the free-running frame counter
;   $BA      GameState     0 = play, 1 = win, 2 = lose
;   $BB      Temp          scratch
;   $BC      CurP0         the current P0 graphics byte ($3C or 0)
;   $BD      CurP1         the current P1 graphics byte ($FF or 0)
;   $BE      CurM0         the current ENAM0 byte ($02 or 0)
;   $BF      CurBall       the current ENABL byte ($02 or 0)
;   $C0      P0Row         the player's first object row (PlayerRow * 4)
;   $C1      P1Row
;   $C2      M0Row
;   $C3      BallRow
;   $C4      P0RowEnd      P0Row + 4
;   $C5      P1RowEnd
;   $C6      M0RowEnd
;   $C7      BallRowEnd    BallRow + 2
;   $C8      PFIdx         the next maze row for LoadFogPF, 0..11
;   $C9      PF0Val        the current maze row's PF bytes
;   $CA      PF1Val
;   $CB      PF2Val
;   $CC      TempCol       the target / enemy cell column
;   $CD      TempRow       the target / enemy cell row
;   $CE      TempDir       the direction
;   $CF      TempU         the unique column during a wall check
;   $D0      TempByte      the wall-map byte during a wall check
;   $D1      TargetCol     the enemy's target column
;   $D2      TargetRow     the enemy's target row
;   $D3      DeltaX        PlayerCol - enemy column, signed
;   $D4      DeltaY        PlayerRow - enemy row, signed
;   $D5      AbsX          |DeltaX|
;   $D6      AbsY          |DeltaY|
;   $D7      WhichEnemy    0 or 1
;   $D8      IdleTimer     frames with no joystick direction
;   $D9      DemoCount     the demo's per-step countdown
;   $DA      DemoStep      the next DemoPath index
;   $DB      IconPF0       the status band's PF bytes
;   $DC      IconPF1
;   $DD      IconPF2
;   $DE-$EC  FogPF         15 bytes: the five visible rows x 3 PF bytes
;   $ED-$F7  FogIndex      11 bytes: row -> window index (0,3,6,9,12,$FF)
;   $F8-$FF  stack
;
; Controls:
;   Left joystick: up/down/left/right moves the player one cell.
;   Fire restarts after the win or the lose.
;
; Checkpoints (the A/X/Y/SP values are the state at the label):
;   StartFrame (259/3), VblankStart (0/5), BodyStart (37/5),
;   MazeRowStart (53, picture line 16), OverscanStart (229),
;   PlayerCell (A=PlayerCol, X=PlayerRow), MoveTry (A=the direction),
;   WallRead (A=the wall-map byte), KeyGet (A=the new KeysLeft),
;   EnemyStep (A=the enemy, 0 or 1), GameStateRead (A=GameState),
;   ObjRowWrite (A=the byte at ObjRowTable+0).
;
; Build: acme -f plain -o build/lesson71.bin \
;        lessons/part10-capstones/71-maze-explorer/71-maze-explorer.asm
; Run:   stella build/lesson71.bin
; =============================================================================

    !cpu 6502

    !source "include/vcs.asm"
    !source "include/macro.asm"

; =============================================================================
; PROGRAM CONSTANTS
; =============================================================================
VBLANK_TIMER   = 44       ; 1 + 43 x 64 = 2753 cycles = 36.2 lines; the
                          ; timer + wait_timer's WSYNC make the measured 37-line VBLANK
OVERSCAN_TIMER = 36       ; 1 + 35 x 64 = 2241 cycles = 29.5 lines; the
                          ; timer + WSYNC make the measured 30-line overscan

STATUS_LINES   = 8        ; the key-icon band: eight 8-line blocks
MAZE_ROWS      = 11       ; picture lines 16-191: 11 x 16
OBJ_ROWS       = 44       ; 11 maze rows x 4 four-line object rows
MAZE_COLS_VIS  = 20       ; 10 unique columns, mirrored by reflect mode

MOVE_DELAY     = 8        ; a held joystick direction repeats every 8 frames
ENEMY_DELAY    = 8        ; both enemies step every 8 frames

P0_BIAS        = 3        ; the Lesson 26 player positioning bias
P1_BIAS        = 3
M0_BIAS        = 4        ; missiles and the ball output one clock earlier
BL_BIAS        = 4

C_WALL         = $96      ; the maze walls, the key icons, the ball/key: blue
C_PLAYER       = $1E      ; P0 and M0: gold (the player's bar, enemy 2)
C_ENEMY        = $46      ; P1 and M1: red
C_WIN          = $C8      ; the win flash: green
C_LOSE         = $46      ; the lose flash: red
C_BG           = $00      ; black

PLAYER_GLYPH   = $3C      ; P0's 16-line solid bar: a 4-pixel-wide player
ENEMY_GLYPH    = $FF      ; P1's 16-line solid block
MISSILE_ON     = $02      ; ENAM0's enable bit
BALL_ON        = $02      ; ENABL's enable bit

; =============================================================================
; RAM ALLOCATION ($80-$DD, plus FogPF $DE-$EC and FogIndex $ED-$F7; the stack is $F8-$FF)
; =============================================================================
ObjRowTable = $80         ; 44 bytes ($80-$AB)

PlayerCol   = $AC
PlayerRow   = $AD
PrevJoy     = $AE
MoveTimer   = $AF
Enemy1Col   = $B0
Enemy1Row   = $B1
Enemy2Col   = $B2
Enemy2Row   = $B3
EnemyTimer  = $B4
KeyCol      = $B5
KeyRow      = $B6
KeysLeft    = $B7
KeyIndex    = $B8
Frame       = $B9
GameState   = $BA
Temp        = $BB
CurP0       = $BC
CurP1       = $BD
CurM0       = $BE
CurBall     = $BF
P0Row       = $C0
P1Row       = $C1
M0Row       = $C2
BallRow     = $C3
P0RowEnd    = $C4
P1RowEnd    = $C5
M0RowEnd    = $C6
BallRowEnd  = $C7

PFIdx       = $C8
PF0Val      = $C9
PF1Val      = $CA
PF2Val      = $CB
TempCol     = $CC
TempRow     = $CD
TempDir     = $CE
TempU       = $CF
TempByte    = $D0
TargetCol   = $D1
TargetRow   = $D2
DeltaX      = $D3
DeltaY      = $D4
AbsX        = $D5
AbsY        = $D6
WhichEnemy  = $D7
IdleTimer   = $D8
DemoCount   = $D9
DemoStep    = $DA
IconPF0     = $DB
IconPF1     = $DC
IconPF2     = $DD
FogPF       = $DE         ; 15 bytes: the five visible rows x 3 PF bytes
FogIndex    = $ED         ; 11 bytes: row -> window index (0,3,6,9,12,$FF)

; =============================================================================
; ROM START — cartridge space ($F000-$FFFF)
; =============================================================================
    * = $F000

; =============================================================================
; RESET — the program's entry point
; =============================================================================
Reset:
    +clean_start
    LDA #$00
    STA SWACNT              ; port A is an input port (the joystick)

    LDA #C_PLAYER
    STA COLUP0              ; P0 and M0: gold (the player's bar, enemy 2)
    LDA #C_ENEMY
    STA COLUP1              ; P1: red (enemy 1)
    LDA #C_WALL
    STA COLUPF              ; the walls, the key icons, and the ball/key
    LDA #C_BG
    STA COLUBK
    LDA #$31
    STA CTRLPF              ; reflect mode (bit 0) + an 8-pixel ball (bits 4-5)
    LDA #$30
    STA NUSIZ0              ; missile 0 is 8 pixels wide (enemy 2)
    LDA #$00
    STA NUSIZ1
    STA REFP0
    STA REFP1
    STA PF0
    STA PF1
    STA PF2
    STA GRP0
    STA GRP1
    STA ENABL
    STA ENAM0
    LDA #$01
    STA VDELP0              ; VDEL: P0's and the ball's graphics written on
    STA VDELBL              ; line n display on line n+1.  P1 is written
                            ; immediately on its object row's first line.
    LDA #$00
    STA VDELP1              ; P1 has no vertical delay

    JSR ResetGame
    JSR BuildFog            ; the first frame's window (the overscan rebuilds it)

; =============================================================================
; FRAME — 3 VSYNC + 37 VBLANK + 192 picture + 30 overscan = 262 lines
; =============================================================================
StartFrame:                 ; checkpoint: scanline 259, the first VSYNC line
    +vsync

VblankStart:                ; checkpoint: scanline 0, the first VBLANK line
    LDA #$02
    STA VBLANK              ; blank the picture while the game thinks
    +set_timer VBLANK_TIMER
    INC Frame

; The status band uses only PF blocks; the sprite latches must be empty.
; VDEL delays the three writes below by one line, so the first visible line
; shows the cleared graphics.
    LDA #$00
    STA PF0
    STA PF1
    STA PF2
    STA GRP0
    STA GRP1
    STA ENABL
    STA ENAM0

; -----------------------------------------------------------------------------
; 1. THE STATUS BAND'S ICON BYTES (from KeysLeft, 0..3)
; -----------------------------------------------------------------------------
    LDA KeysLeft
    ASL
    CLC
    ADC KeysLeft            ; KeysLeft * 3
    TAY
    LDA IconTable,Y
    STA IconPF0
    LDA IconTable+1,Y
    STA IconPF1
    LDA IconTable+2,Y
    STA IconPF2

; -----------------------------------------------------------------------------
; 2. INPUT: THE JOYSTICK, THE SCRIPTED DEMO, OR THE FIRE RESTART
; -----------------------------------------------------------------------------
    JSR ReadInput

; -----------------------------------------------------------------------------
; 3. THE ENEMIES: BOTH STEP EVERY EIGHT FRAMES AND THE CELLS ARE COMPARED
; -----------------------------------------------------------------------------
    JSR EnemyMove

; -----------------------------------------------------------------------------
; 4. THE 44-BYTE OBJECT ROW TABLE
; -----------------------------------------------------------------------------
    JSR BuildObjRows

; -----------------------------------------------------------------------------
; 5. THE WALL COLOUR (AND THE WIN/LOSE FLASH)
; -----------------------------------------------------------------------------
    JSR SetWallColour

; -----------------------------------------------------------------------------
; 6. THE FOUR POSITIONERS (in VBLANK, so the visible block stays eight lines)
; -----------------------------------------------------------------------------
; Each SetCoarse routine starts on a fresh line, so the four divides and the
; one HMOVE take five VBLANK lines.  Positioning here instead of in the
; visible area gives the four divides the whole line; in the visible block a
; divide that reaches the right edge (the 156-cycle target) would spill into
; the next line and grow the frame by one.
    LDA PlayerCol
    ASL
    ASL
    ASL                     ; X = PlayerCol * 8
    CLC
    ADC #P0_BIAS
    JSR SetCoarseP0
    LDA Enemy1Col
    ASL
    ASL
    ASL
    CLC
    ADC #P1_BIAS
    JSR SetCoarseP1
    LDA Enemy2Col
    ASL
    ASL
    ASL
    CLC
    ADC #M0_BIAS
    JSR SetCoarseM0
    LDA KeyCol
    ASL
    ASL
    ASL
    CLC
    ADC #BL_BIAS
    JSR SetCoarseBL
    STA WSYNC
    STA HMOVE               ; one HMOVE applies all four fine offsets

    +wait_timer
    LDA #$00
    STA VBLANK              ; picture on

; =============================================================================
; VISIBLE 0-7 — THE STATUS BAND: THREE KEY ICONS (AND THEIR MIRRORS)
; =============================================================================
BodyStart:                  ; checkpoint: scanline 37, picture line 0
    LDA IconPF0
    STA PF0
    LDA IconPF1
    STA PF1
    LDA IconPF2
    STA PF2
    LDX #STATUS_LINES
StatusLoop:
    STA WSYNC
    DEX
    BNE StatusLoop

; =============================================================================
; VISIBLE 8-15 — THE FIRST MAZE ROW'S SETUP (EIGHT BLANK/SETUP LINES)
; =============================================================================
; The positioners already ran in VBLANK.  Line 8 clears the icon playfield;
; line 9 loads the fog window's row 0; lines 10-12 are blank; line 13 decodes
; object row 0; line 14 clears the graphics latches; line 15 writes the ball
; and P0 (VDEL puts them on line 16).  P1 is written immediately on line 16's
; first line.  The maze starts on picture line 16, scanline 53.
    LDA #$00
    STA PF0
    STA PF1
    STA PF2
    STA WSYNC               ; line 8 -> 9

    LDA #$00
    STA PFIdx               ; LoadFogPF starts at row 0
    JSR LoadFogPF
    STA WSYNC               ; line 9 -> 10

    STA WSYNC               ; line 10 -> 11
    STA WSYNC               ; line 11 -> 12
    STA WSYNC               ; line 12 -> 13

    ; line 13: decode object row 0 (the fog load used line 9)
    LDA ObjRowTable
    TAY
    LDA ObjP0Tab,Y
    STA CurP0
    LDA ObjP1Tab,Y
    STA CurP1
    LDA ObjM0Tab,Y
    STA CurM0
    LDA ObjBLTab,Y
    STA CurBall
    STA WSYNC               ; line 13 -> 14

    ; line 14: clear the graphics latch (VDEL puts the zero on line 15)
    LDA #$00
    STA GRP0
    STA GRP1
    STA ENABL
    STA WSYNC               ; line 14 -> 15

    ; line 15: write object row 0's ball and P0 at the top of the line.  VDEL
    ; displays them on line 16; P1 is written immediately on line 16's first
    ; line, so it needs no setup store.  The ball is stored first because the
    ; third key can sit on row 0.
    LDA CurBall
    STA ENABL
    LDA CurP0
    STA GRP0
    STA WSYNC               ; line 15 -> line 16
    NOP                     ; the label must not sit inside the WSYNC halt

; =============================================================================
; VISIBLE 16-191 — THE MAZE: 11 ROWS x 16 LINES, 44 OBJECT ROWS x 4 LINES
; =============================================================================
; Each object row is four lines.  Line 1 writes P1 (immediate) and the
; missile; on the first object row of a maze row it also stores the three PF
; bytes.  The ten later maze rows enter the loop at cycle 0, so the five
; stores complete at 6 (PF0), 12 (P1), 18 (ENAM0), 25 (PF1) and 32 (PF2).
; The first maze row runs MazeRowStart's LDX first (Stella reports 53/2), so
; its completions are 8/14/20/27/34; the deadlines are 22.7, 22.7, 22.7,
; 28.0 and 38.7 (PF1 keeps one cycle on the first row).  The other object
; rows store only P1 and ENAM0, at 6 and 12.  Line 2 decodes the next object row;
; line 3 prefetches the next maze row's PF; line 4 writes P0 and the ball
; for the next row (VDEL displays them on its first line).
MazeRowStart:               ; checkpoint: scanline 53, picture line 16
    LDX #0                  ; the object-row index, 0..43
MazeRowLoop:
    ; --- object row 0, line 1: the PF bytes + P1 + ENAM0 --------------------
    ; The first line of a maze row starts at cycle 0 (the LDX is on line 15),
    ; so the five stores complete at 6/12/18/25/32: PF0 6, P1 12, ENAM0 18,
    ; PF1 25, PF2 32.  The deadlines are 22.7/22.7/22.7/28.0/38.7.
    LDA PF0Val
    STA PF0
    LDA CurP1
    STA GRP1                ; P1 is immediate (VDELP1 is off)
    LDA CurM0
    STA ENAM0
    LDA PF1Val
    STA PF1
    LDA PF2Val
    STA PF2
    STA WSYNC               ; line 1
    ; line 2: decode the next object row
    LDA ObjRowTable+1,X
    TAY
    LDA ObjP0Tab,Y
    STA CurP0
    LDA ObjP1Tab,Y
    STA CurP1
    LDA ObjM0Tab,Y
    STA CurM0
    LDA ObjBLTab,Y
    STA CurBall
    STA WSYNC               ; line 2
    STA WSYNC               ; line 3
    ; line 4: P0 and the ball for the next row (VDEL)
    LDA CurP0
    STA GRP0
    LDA CurBall
    STA ENABL
    STA WSYNC               ; line 4
    INX

    ; --- object row 1 -------------------------------------------------------
    LDA CurP1
    STA GRP1
    LDA CurM0
    STA ENAM0
    STA WSYNC               ; line 1
    LDA ObjRowTable+1,X
    TAY
    LDA ObjP0Tab,Y
    STA CurP0
    LDA ObjP1Tab,Y
    STA CurP1
    LDA ObjM0Tab,Y
    STA CurM0
    LDA ObjBLTab,Y
    STA CurBall
    STA WSYNC               ; line 2
    STA WSYNC               ; line 3
    LDA CurP0
    STA GRP0
    LDA CurBall
    STA ENABL
    STA WSYNC               ; line 4
    INX

    ; --- object row 2 -------------------------------------------------------
    LDA CurP1
    STA GRP1
    LDA CurM0
    STA ENAM0
    STA WSYNC               ; line 1
    LDA ObjRowTable+1,X
    TAY
    LDA ObjP0Tab,Y
    STA CurP0
    LDA ObjP1Tab,Y
    STA CurP1
    LDA ObjM0Tab,Y
    STA CurM0
    LDA ObjBLTab,Y
    STA CurBall
    STA WSYNC               ; line 2
    STA WSYNC               ; line 3
    LDA CurP0
    STA GRP0
    LDA CurBall
    STA ENABL
    STA WSYNC               ; line 4
    INX

    ; --- object row 3: the last row of the maze row --------------------------
    LDA CurP1
    STA GRP1
    LDA CurM0
    STA ENAM0
    STA WSYNC               ; line 1
    CPX #(OBJ_ROWS - 1)
    BEQ MazeLastDecode
    LDA ObjRowTable+1,X
    TAY
    LDA ObjP0Tab,Y
    STA CurP0
    LDA ObjP1Tab,Y
    STA CurP1
    LDA ObjM0Tab,Y
    STA CurM0
    LDA ObjBLTab,Y
    STA CurBall
MazeLastDecode:
    STA WSYNC               ; line 2
    ; line 3: prefetch the next maze row's PF bytes
    CPX #(OBJ_ROWS - 1)
    BEQ MazeNoPrefetch
    JSR LoadFogPF
MazeNoPrefetch:
    STA WSYNC               ; line 3
    LDA CurP0
    STA GRP0
    LDA CurBall
    STA ENABL
    STA WSYNC               ; line 4
    INX
    CPX #OBJ_ROWS
    BEQ MazeKernelDone
    JMP MazeRowLoop
MazeKernelDone:
    ; 11 maze rows x 16 lines = 176; the last WSYNC releases at scanline 229.



; =============================================================================
; OVERSCAN — 30 lines, then the next frame
; =============================================================================
OverscanStart:              ; checkpoint: scanline 229
    LDA #$02
    STA VBLANK
    +set_timer OVERSCAN_TIMER
    JSR BuildFog            ; the next frame's window (14 lines of the overscan)
    +wait_timer
    JMP StartFrame

; =============================================================================
; READ INPUT — the joystick, the scripted demo, or the fire restart
; =============================================================================
; SWCHA's P0 high nibble is active low: bit 4 up, 5 down, 6 left, 7 right.
; A held direction repeats every MOVE_DELAY frames.  With no direction for
; DEMO_START frames the DemoPath takes over, one cell every DemoPeriod
; frames.  Any direction resets the idle timer and the demo.
ReadInput:
    LDA GameState
GameStateRead:              ; checkpoint: A = GameState
    BNE GameOverInput

    LDA SWCHA
    AND #$F0
    CMP #$F0
    BNE ManualInput

    ; --- no direction: count the idle frames, then follow the demo path ---
    LDA #$FF
    STA PrevJoy
    LDA IdleTimer
    CMP #DemoStart
    BCS DemoTick
    INC IdleTimer
    RTS
DemoTick:
    DEC DemoCount
    BNE ReadDone
    LDA #DemoPeriod
    STA DemoCount
    LDX DemoStep
    CPX #DemoSteps
    BCS ReadDone
    LDA DemoPath,X
    INC DemoStep
    JSR TryMove
    RTS

    ; --- a direction is held: manual control ---
ManualInput:
    LDA #$00
    STA IdleTimer
    STA DemoStep
    LDA #DemoPeriod
    STA DemoCount
    LDA SWCHA
    AND #$F0
    CMP PrevJoy
    BEQ ManualSame
    LDA #$00
    STA MoveTimer           ; a new direction moves immediately
ManualSame:
    LDA SWCHA
    AND #$F0
    STA PrevJoy
    LDA MoveTimer
    BNE ManualCount
    LDA #(MOVE_DELAY - 1)   ; the reload plus this frame makes 8
    STA MoveTimer
    JSR DirFromJoy
    JSR TryMove
    RTS
ManualCount:
    DEC MoveTimer
ReadDone:
    RTS

; --- the win or the lose: fire restarts ---
GameOverInput:
    LDA INPT4
    AND #$80                ; bit 7 is 0 while fire is pressed
    BNE ReadDone
    JSR ResetGame
    RTS

; =============================================================================
; DIR FROM JOY — A = 0 up, 1 down, 2 left, 3 right
; =============================================================================
DirFromJoy:
    LDA SWCHA
    AND #$10
    BEQ DirUp
    LDA SWCHA
    AND #$20
    BEQ DirDown
    LDA SWCHA
    AND #$40
    BEQ DirLeft
    LDA SWCHA
    AND #$80
    BEQ DirRight
    LDA #$FF                ; no direction (the caller checked already)
    RTS
DirUp:
    LDA #$00
    RTS
DirDown:
    LDA #$01
    RTS
DirLeft:
    LDA #$02
    RTS
DirRight:
    LDA #$03
    RTS

; =============================================================================
; TRY MOVE — A = the direction; the player moves one cell if it is open
; =============================================================================
TryMove:
MoveTry:                    ; checkpoint: A = the direction
    STA TempDir
    LDA PlayerCol
    LDX PlayerRow
PlayerCell:                 ; checkpoint: A = PlayerCol, X = PlayerRow
    STA TempCol
    STX TempRow
    LDX TempDir
    CPX #$00
    BEQ TryUp
    CPX #$01
    BEQ TryDown
    CPX #$02
    BEQ TryLeft
    ; right
    LDA TempCol
    CMP #(MAZE_COLS_VIS - 1)
    BCS MoveBlocked
    CLC
    ADC #1
    STA TempCol
    JMP CheckTarget
TryUp:
    LDA TempRow
    BEQ MoveBlocked
    DEC TempRow
    JMP CheckTarget
TryDown:
    LDA TempRow
    CMP #(MAZE_ROWS - 1)
    BCS MoveBlocked
    INC TempRow
    JMP CheckTarget
TryLeft:
    LDA TempCol
    BEQ MoveBlocked
    DEC TempCol
CheckTarget:
    ; the target's visible column maps to the unique wall-map column
    LDA TempCol
    CMP #(MAZE_COLS_VIS / 2)
    BCC HaveUnique
    LDA #(MAZE_COLS_VIS - 1)
    SEC
    SBC TempCol
HaveUnique:
    LDX TempRow
    JSR WallCheck           ; A = the wall byte, Z = 1 when open
    BNE MoveBlocked
    LDA TempCol
    STA PlayerCol
    LDA TempRow
    STA PlayerRow
    ; the player can walk into an enemy's cell; the cell compare must run
    ; after this move, not only after the enemies move
    JSR CheckCollision
    LDA GameState
    BNE MoveDone
    JMP CheckKeys
MoveDone:
    RTS
MoveBlocked:
    RTS

; =============================================================================
; CHECK KEYS — the player entered the current key's cell?
; =============================================================================
CheckKeys:
    LDA PlayerCol
    CMP KeyCol
    BNE KeysDone
    LDA PlayerRow
    CMP KeyRow
    BNE KeysDone
    INC KeysLeft
    LDA KeysLeft
KeyGet:                     ; checkpoint: A = the new KeysLeft
    CMP #KeyCount
    BCS WinGame
    INC KeyIndex
    LDA KeyIndex
    ASL                     ; KeyIndex * 2
    TAX
    LDA KeyCells,X
    STA KeyCol
    LDA KeyCells+1,X
    STA KeyRow
KeysDone:
    RTS
WinGame:
    LDA #1
    STA GameState
    RTS

; =============================================================================
; WALL CHECK — A = the unique column, X = the row; Z = 1 when open
; =============================================================================
; The wall map's 10 bits are split over two bytes per row.  The first byte
; holds bits 9..2 (unique column 0 in bit 7); the second holds bits 1..0
; (column 8 in bit 1, column 9 in bit 0).  The 10-entry WallMask table turns
; the unique column into its bit.  1 = wall, so Z = 1 (the AND result 0)
; means the cell is open.
WallCheck:
    STA TempU
    TXA
    ASL                     ; row * 2
    TAX
    LDA TempU
    CMP #8
    BCS WallLow
    TAY
    LDA MazeWalls,X
    JMP WallHave
WallLow:
    SEC
    SBC #8
    TAY
    LDA MazeWalls+1,X
WallHave:
WallRead:                   ; checkpoint: A = the wall-map byte
    STA TempByte
    LDA TempU
    TAY
    LDA WallMask,Y
    AND TempByte
    RTS

; =============================================================================
; ENEMY MOVE — both enemies step every eight frames, then the cells compare
; =============================================================================
EnemyMove:
    LDA GameState
    BNE EnemyDone           ; the win and the lose freeze the enemies
    DEC EnemyTimer
    BNE EnemyDone
    LDA #ENEMY_DELAY
    STA EnemyTimer
    LDA #0
    JSR EnemyOne
    LDA #1
    JSR EnemyOne
    JSR CheckCollision
EnemyDone:
    RTS

; -----------------------------------------------------------------------------
; ENEMY ONE — A = the enemy (0 or 1); greedy step toward the player
; -----------------------------------------------------------------------------
EnemyOne:
EnemyStep:                  ; checkpoint: A = the enemy (0 or 1)
    STA WhichEnemy
    LDA WhichEnemy
    BNE EnemyTwoCell
    LDA Enemy1Col
    STA TempCol
    LDA Enemy1Row
    STA TempRow
    JMP EnemyHaveCell
EnemyTwoCell:
    LDA Enemy2Col
    STA TempCol
    LDA Enemy2Row
    STA TempRow
EnemyHaveCell:
    ; DeltaX = PlayerCol - enemy column; DeltaY = PlayerRow - enemy row
    LDA PlayerCol
    SEC
    SBC TempCol
    STA DeltaX
    LDA PlayerRow
    SEC
    SBC TempRow
    STA DeltaY

    ; |DeltaX| and |DeltaY|
    LDA DeltaX
    BPL EnemyDxAbs
    EOR #$FF
    CLC
    ADC #1
EnemyDxAbs:
    STA AbsX
    LDA DeltaY
    BPL EnemyDyAbs
    EOR #$FF
    CLC
    ADC #1
EnemyDyAbs:
    STA AbsY

    ; An enemy on the player's cell must not step off it: the collision is a
    ; cell compare, so a zero delta means the catch has already happened.
    LDA AbsX
    ORA AbsY
    BNE EnemyMoveOn
    RTS
EnemyMoveOn:

    ; The axis with the larger distance goes first; a tie tries vertical.
    LDA AbsX
    CMP AbsY
    BCC EnemyVerticalFirst
    BEQ EnemyVerticalFirst

    ; --- horizontal first ---
    LDA DeltaX
    BMI EnemyHorizLeft
    LDA #3
    JMP EnemyTryHoriz
EnemyHorizLeft:
    LDA #2
EnemyTryHoriz:
    JSR EnemyTry
    BCS EnemyMoved
    ; blocked: try vertical
    LDA DeltaY
    BMI EnemyVertUp
    LDA #1
    JMP EnemyTryVert
EnemyVertUp:
    LDA #0
EnemyTryVert:
    JSR EnemyTry
    BCS EnemyMoved
    RTS                     ; both blocked: stay

    ; --- vertical first ---
EnemyVerticalFirst:
    LDA DeltaY
    BMI EnemyVertUp2
    LDA #1
    JMP EnemyTryVert2
EnemyVertUp2:
    LDA #0
EnemyTryVert2:
    JSR EnemyTry
    BCS EnemyMoved
    LDA DeltaX
    BMI EnemyHorizLeft2
    LDA #3
    JMP EnemyTryHoriz2
EnemyHorizLeft2:
    LDA #2
EnemyTryHoriz2:
    JSR EnemyTry
    BCS EnemyMoved
    RTS                     ; both blocked: stay

EnemyMoved:
    ; commit the target cell to the enemy
    LDA WhichEnemy
    BNE EnemyMovedTwo
    LDA TempCol
    STA Enemy1Col
    LDA TempRow
    STA Enemy1Row
    RTS
EnemyMovedTwo:
    LDA TempCol
    STA Enemy2Col
    LDA TempRow
    STA Enemy2Row
    RTS

; =============================================================================
; ENEMY TRY — A = the direction; TempCol/TempRow = the enemy's cell
; =============================================================================
; Returns C = 1 and updates TempCol/TempRow when the target cell is open;
; C = 0 when the target is outside the grid or a wall.
EnemyTry:
    STA TempDir
    LDA TempCol
    STA TargetCol
    LDA TempRow
    STA TargetRow
    LDX TempDir
    CPX #$00
    BEQ ETryUp
    CPX #$01
    BEQ ETryDown
    CPX #$02
    BEQ ETryLeft
    ; right
    LDA TargetCol
    CMP #(MAZE_COLS_VIS - 1)
    BCS ETryBlocked
    INC TargetCol
    JMP ETryCheck
ETryUp:
    LDA TargetRow
    BEQ ETryBlocked
    DEC TargetRow
    JMP ETryCheck
ETryDown:
    LDA TargetRow
    CMP #(MAZE_ROWS - 1)
    BCS ETryBlocked
    INC TargetRow
    JMP ETryCheck
ETryLeft:
    LDA TargetCol
    BEQ ETryBlocked
    DEC TargetCol
ETryCheck:
    LDA TargetCol
    CMP #(MAZE_COLS_VIS / 2)
    BCC ETryUnique
    LDA #(MAZE_COLS_VIS - 1)
    SEC
    SBC TargetCol
ETryUnique:
    ; The AI's JSR chain (EnemyMove -> EnemyOne -> EnemyTry -> WallCheck)
    ; would push a return address onto $F7, which is FogIndex's last byte.
    ; The wall check is inlined here so the stack stays above $F9.
    LDX TargetRow
    STA TempU
    TXA
    ASL
    TAX
    LDA TempU
    CMP #8
    BCS ETryWallLow
    TAY
    LDA MazeWalls,X
    JMP ETryWallHave
ETryWallLow:
    SEC
    SBC #8
    TAY
    LDA MazeWalls+1,X
ETryWallHave:
    STA TempByte
    LDA TempU
    TAY
    LDA WallMask,Y
    AND TempByte
    BNE ETryBlocked
    LDA TargetCol
    STA TempCol
    LDA TargetRow
    STA TempRow
    SEC
    RTS
ETryBlocked:
    CLC
    RTS

; =============================================================================
; CHECK COLLISION — an enemy in the player's cell loses
; =============================================================================
CheckCollision:
    LDA Enemy1Col
    CMP PlayerCol
    BNE CheckEnemy2
    LDA Enemy1Row
    CMP PlayerRow
    BEQ LoseGame
CheckEnemy2:
    LDA Enemy2Col
    CMP PlayerCol
    BNE CollisionDone
    LDA Enemy2Row
    CMP PlayerRow
    BNE CollisionDone
LoseGame:
    LDA #2
    STA GameState
CollisionDone:
    RTS

; =============================================================================
; BUILD OBJECT ROWS — clear 44 bytes, then OR the four object ranges
; =============================================================================
; A 16-line character fills one maze row: four 4-line object rows.  The key
; is 8 lines tall, so it sets two object rows starting at KeyRow * 4 + 1.
BuildObjRows:
    LDX #0
    LDA #$00
ObjClear:
    STA ObjRowTable,X
    INX
    CPX #OBJ_ROWS
    BNE ObjClear

    ; the player: bit 0
    LDA PlayerRow
    ASL
    ASL
    STA P0Row
    CLC
    ADC #4
    STA P0RowEnd
    LDX P0Row
ObjP0:
    LDA ObjRowTable,X
    ORA #$01
    STA ObjRowTable,X
    INX
    CPX P0RowEnd
    BNE ObjP0

    ; enemy 1: bit 1
    LDA Enemy1Row
    ASL
    ASL
    STA P1Row
    CLC
    ADC #4
    STA P1RowEnd
    LDX P1Row
ObjP1:
    LDA ObjRowTable,X
    ORA #$02
    STA ObjRowTable,X
    INX
    CPX P1RowEnd
    BNE ObjP1

    ; enemy 2: bit 2
    LDA Enemy2Row
    ASL
    ASL
    STA M0Row
    CLC
    ADC #4
    STA M0RowEnd
    LDX M0Row
ObjM0:
    LDA ObjRowTable,X
    ORA #$04
    STA ObjRowTable,X
    INX
    CPX M0RowEnd
    BNE ObjM0

    ; the key: bit 3, two 4-line rows (8 pixels tall), centred in the cell.
    ; The key blinks on Frame bit 4: the 8x8 block shares COLUPF with the
    ; walls, and a blink makes the item read even when it touches a wall.
    LDA Frame
    AND #$10
    BNE ObjKeyDone
    LDA KeyRow
    ASL
    ASL
    CLC
    ADC #1
    STA BallRow
    CLC
    ADC #2
    STA BallRowEnd
    LDX BallRow
ObjBall:
    LDA ObjRowTable,X
    ORA #$08
    STA ObjRowTable,X
    INX
    CPX BallRowEnd
    BNE ObjBall
ObjKeyDone:

    LDA ObjRowTable
ObjRowWrite:                ; checkpoint: A = the byte at ObjRowTable+0
    RTS

; =============================================================================
; BUILD FOG — the five-row visibility window and the 11-byte row index
; =============================================================================
; FogIndex[row] is (row - PlayerRow + 2) * 3 for the five rows within two of
; the player, and $FF for every other row.  The window rows are computed
; from the player's cell: a row at vertical distance d has a horizontal
; allowance of 2 - d, so the visible columns are PlayerCol - (2 - d) through
; PlayerCol + (2 - d), clamped to 0..19.  Each visible column maps to its
; unique cell with the mirror transform; CellPF0/1/2 give the cell's two
; chunks.  The three masks are ANDed with the row's static MazePF bytes.
BuildFog:
    LDX #0
FogIndexLoop:
    TXA
    SEC
    SBC PlayerRow
    CMP #$FE
    BCC FogIndexPositive
    JMP FogIndexIn          ; A = $FE or $FF: -2 or -1
FogIndexPositive:
    CMP #3
    BCS FogIndexOut         ; A >= 3
FogIndexIn:
    CLC
    ADC #2                  ; the window index, 0..4
    STA Temp
    ASL
    CLC
    ADC Temp                ; * 3
    STA FogIndex,X
    JMP FogIndexNext
FogIndexOut:
    LDA #$FF
    STA FogIndex,X
FogIndexNext:
    INX
    CPX #11
    BNE FogIndexLoop

    LDX #0                  ; the window index (dr + 2), 0..4
FogWindowLoop:
    TXA
    CLC
    ADC PlayerRow
    SEC
    SBC #2
    STA TempRow             ; the row, -2..12 in signed terms
    CMP #11
    BCC FogWindowRow
    JMP FogWindowDark       ; negative or past row 10
FogWindowRow:
    LDA FogH,X
    STA AbsY                ; the horizontal allowance h

    ; lo = max(0, PlayerCol - h)
    LDA PlayerCol
    SEC
    SBC AbsY
    BCS FogLoOk
    LDA #0
FogLoOk:
    STA TempCol
    ; hi = min(19, PlayerCol + h)
    LDA PlayerCol
    CLC
    ADC AbsY
    CMP #20
    BCC FogHiOk
    LDA #19
FogHiOk:
    STA DeltaX
    ; the three mask bytes: DeltaY = PF0, AbsX = PF1, Temp = PF2
    LDA #0
    STA DeltaY
    STA AbsX
    STA Temp
    ; the visible column loop: count = hi - lo + 1
    LDA DeltaX
    SEC
    SBC TempCol
    STA TargetRow
    LDA TempCol
    STA TargetCol
FogCellLoop:
    LDA TargetCol
    CMP #10
    BCC FogCellUnique
    LDA #19
    SEC
    SBC TargetCol
FogCellUnique:
    TAY
    LDA CellPF0,Y
    ORA DeltaY
    STA DeltaY
    LDA CellPF1,Y
    ORA AbsX
    STA AbsX
    LDA CellPF2,Y
    ORA Temp
    STA Temp
    INC TargetCol
    DEC TargetRow
    BPL FogCellLoop

    ; window offset = X * 3
    TXA
    ASL
    STA TargetCol
    TXA
    CLC
    ADC TargetCol
    STA TargetCol
    ; static PF offset = row * 3
    LDA TempRow
    ASL
    STA TargetRow
    LDA TempRow
    CLC
    ADC TargetRow
    STA TargetRow
    LDY TargetRow
    LDA MazePF,Y
    AND DeltaY
    LDY TargetCol
    STA FogPF,Y
    LDY TargetRow
    LDA MazePF+1,Y
    AND AbsX
    LDY TargetCol
    STA FogPF+1,Y
    LDY TargetRow
    LDA MazePF+2,Y
    AND Temp
    LDY TargetCol
    STA FogPF+2,Y
    JMP FogWindowNext
FogWindowDark:
    TXA
    ASL
    STA TargetCol
    TXA
    CLC
    ADC TargetCol
    TAY
    LDA #0
    STA FogPF,Y
    STA FogPF+1,Y
    STA FogPF+2,Y
FogWindowNext:
    INX
    CPX #5
    BEQ FogWindowDone
    JMP FogWindowLoop
FogWindowDone:
    RTS

; =============================================================================
; LOAD FOG PF — turn the next maze row into the three PF bytes
; =============================================================================
; PFIdx is the row, 0..11.  FogIndex maps it to the window offset or $FF;
; a dark row loads three zeros.  X is preserved for the kernel's object-row
; index; Y and A are scratch.
LoadFogPF:
    LDY PFIdx
    LDA FogIndex,Y
    CMP #$FF
    BEQ LoadFogDark
    TAY
    LDA FogPF,Y
    STA PF0Val
    LDA FogPF+1,Y
    STA PF1Val
    LDA FogPF+2,Y
    STA PF2Val
    INC PFIdx
    RTS
LoadFogDark:
    LDA #$00
    STA PF0Val
    STA PF1Val
    STA PF2Val
    INC PFIdx
    RTS

; =============================================================================
; SET WALL COLOUR — the normal wall colour, or the win/lose flash
; =============================================================================
SetWallColour:
    LDA #C_WALL
    LDX GameState
    BEQ WallColourDone      ; play: the wall colour
    LDA Frame
    AND #$10
    BEQ WallColourNormal    ; the flash's off phase is the wall colour
    LDA #C_WIN
    CPX #1
    BEQ WallColourDone
    LDA #C_LOSE
    JMP WallColourDone
WallColourNormal:
    LDA #C_WALL
WallColourDone:
    STA COLUPF
    RTS

; =============================================================================
; RESET GAME — the shared power-on and fire-restart state
; =============================================================================
ResetGame:
    LDA #MazeStartCol
    STA PlayerCol
    LDA #MazeStartRow
    STA PlayerRow
    LDA #$00
    STA GameState
    STA Frame
    STA KeysLeft
    STA KeyIndex
    STA IdleTimer
    STA DemoStep
    STA MoveTimer
    LDA #$FF
    STA PrevJoy
    LDA #ENEMY_DELAY
    STA EnemyTimer
    LDA #DemoPeriod
    STA DemoCount
    LDA KeyCells
    STA KeyCol
    LDA KeyCells+1
    STA KeyRow
    LDA EnemyCells
    STA Enemy1Col
    LDA EnemyCells+1
    STA Enemy1Row
    LDA EnemyCells+2
    STA Enemy2Col
    LDA EnemyCells+3
    STA Enemy2Row
    RTS

; =============================================================================
; COARSE POSITIONING — the Lesson 26 divide-by-15 routines; no HMOVE here
; =============================================================================
; Input: A = the target X + the object's output bias.  Each routine starts
; on a fresh line, subtracts 15 until the carry clears, turns the negative
; remainder into the signed fine value, stores it in HMxx, and strobes RESxx.
; The caller applies all four fine offsets with one HMOVE.
SetCoarseP0:
    STA WSYNC
    SEC
DivP0:
    SBC #15
    BCS DivP0
    EOR #7
    ASL
    ASL
    ASL
    ASL
    STA HMP0
    STA RESP0
    RTS

SetCoarseP1:
    STA WSYNC
    SEC
DivP1:
    SBC #15
    BCS DivP1
    EOR #7
    ASL
    ASL
    ASL
    ASL
    STA HMP1
    STA RESP1
    RTS

SetCoarseM0:
    STA WSYNC
    SEC
DivM0:
    SBC #15
    BCS DivM0
    EOR #7
    ASL
    ASL
    ASL
    ASL
    STA HMM0
    STA RESM0
    RTS

SetCoarseBL:
    STA WSYNC
    SEC
DivBL:
    SBC #15
    BCS DivBL
    EOR #7
    ASL
    ASL
    ASL
    ASL
    STA HMBL
    STA RESBL
    RTS

; =============================================================================
; THE DECODE TABLES — index a 4-bit object-row byte to the four TIA bytes
; =============================================================================
; Index = bit 3 key, bit 2 enemy 2, bit 1 enemy 1, bit 0 player.  Each table
; is page-aligned so the indexed loads never cross a page.
    !align 255, 0
ObjP0Tab:
    !byte $00, PLAYER_GLYPH, $00, PLAYER_GLYPH
    !byte $00, PLAYER_GLYPH, $00, PLAYER_GLYPH
    !byte $00, PLAYER_GLYPH, $00, PLAYER_GLYPH
    !byte $00, PLAYER_GLYPH, $00, PLAYER_GLYPH
    !align 255, 0
ObjP1Tab:
    !byte $00, $00, ENEMY_GLYPH, ENEMY_GLYPH
    !byte $00, $00, ENEMY_GLYPH, ENEMY_GLYPH
    !byte $00, $00, ENEMY_GLYPH, ENEMY_GLYPH
    !byte $00, $00, ENEMY_GLYPH, ENEMY_GLYPH
    !align 255, 0
ObjM0Tab:
    !byte $00, $00, $00, $00, MISSILE_ON, MISSILE_ON, MISSILE_ON, MISSILE_ON
    !byte $00, $00, $00, $00, MISSILE_ON, MISSILE_ON, MISSILE_ON, MISSILE_ON
    !align 255, 0
ObjBLTab:
    !byte $00, $00, $00, $00, $00, $00, $00, $00
    !byte BALL_ON, BALL_ON, BALL_ON, BALL_ON, BALL_ON, BALL_ON, BALL_ON, BALL_ON

; =============================================================================
; THE WALL MASK TABLE — the 10 unique columns' bits
; =============================================================================
; Columns 0-7 live in the first wall-map byte as bits 7..0; columns 8-9 live
; in the second byte as bits 1..0.  The same mask table serves both bytes.
WallMask:
    !byte $80, $40, $20, $10, $08, $04, $02, $01, $02, $01

; =============================================================================
; THE FOG TABLES — the horizontal allowance and the per-cell PF masks
; =============================================================================
; Window index 0..4 is dr = -2..+2; a row two away has no horizontal
; allowance, a row level with the player has two.  Cell c owns two chunks:
; cell 0 -> PF0 $30, cell 1 -> PF0 $C0, cell 2 -> PF1 $C0, cell 3 -> PF1
; $30, cell 4 -> PF1 $0C, cell 5 -> PF1 $03, cell 6 -> PF2 $03, cell 7 ->
; PF2 $0C, cell 8 -> PF2 $30, cell 9 -> PF2 $C0.
FogH:
    !byte 0, 1, 2, 1, 0
CellPF0:
    !byte $30, $C0, $00, $00, $00, $00, $00, $00, $00, $00
CellPF1:
    !byte $00, $00, $C0, $30, $0C, $03, $00, $00, $00, $00
CellPF2:
    !byte $00, $00, $00, $00, $00, $00, $03, $0C, $30, $C0

; =============================================================================
; THE STATUS ICON TABLE — KeysLeft (0..3) -> three PF bytes
; =============================================================================
; The three slots start at unique cells 2, 5 and 8, visible X=16, 40 and 64.
